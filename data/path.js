  DB.pathIndex = function () {
    if (DB._pathIdx) return DB._pathIdx;
    const idx = {};
    let n = 0;
    DB.path.forEach(function (stage, si) {
      stage.steps.forEach(function (st, ti) {
        n++;
        idx[st.id] = { stage: stage, stageNo: si + 1, stepNo: ti + 1, overall: n, note: st.note };
      });
    });
    Object.keys(idx).forEach(function (k) { idx[k].total = n; });
    DB._pathIdx = idx;
    return idx;
  };

  DB.nextInPath = function (id) {
    const flat = [];
    DB.path.forEach(function (s) { s.steps.forEach(function (st) { flat.push(st.id); }); });
    const i = flat.indexOf(id);
    return (i >= 0 && i < flat.length - 1) ? flat[i + 1] : null;
  };
